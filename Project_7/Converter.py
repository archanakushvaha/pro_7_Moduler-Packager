def km_to_meter(km):
    return km * 1000


def meter_to_km(meter):
    return meter / 1000


def celsius_to_fahrenheit(celsius):
    return (celsius * 9 / 5) + 32


def fahrenheit_to_celsius(fahrenheit):
    return (fahrenheit - 32) * 5 / 9


def kg_to_gram(kg):
    return kg * 1000


def gram_to_kg(gram):
    return gram / 1000
